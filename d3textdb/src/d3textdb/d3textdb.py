    def get_curation_queue(self, project_id: int) -> list[Reference]:
        """Return references in the project that have reached the required
        number of completed annotator snapshots and are ready for curation.
        """
        with Session(self.engine) as session:
            project = session.get(Project, project_id)
            if project is None:
                return []
            threshold = project.required_annotators
            subq = (
                select(AnnotationSnapshot.reference_id)
                .where(AnnotationSnapshot.project_id == project_id)
                .group_by(AnnotationSnapshot.reference_id)
                .having(
                    func.count(func.distinct(AnnotationSnapshot.user_id))
                    >= threshold
                )
                .subquery()
            )
            return list(
                session.scalars(
                    select(Reference).join(
                        subq, subq.c.reference_id == Reference.reference_id
                    )
                ).all()
            )

    def get_annotator_snapshots(
        self, project_id: int, reference_id: int
    ) -> list[AnnotatorSnapshot]:
        """Return the completed annotation snapshots for all annotators on a
        reference within a project.

        Used by the curation view to compare annotations across annotators
        and flag disagreements.
        """
        with Session(self.engine) as session:
            all_snaps = list(
                session.scalars(
                    select(AnnotationSnapshot)
                    .where(AnnotationSnapshot.project_id == project_id)
                    .where(AnnotationSnapshot.reference_id == reference_id)
                    .order_by(AnnotationSnapshot.snapshot_id)
                ).all()
            )
            # Keep only the latest snapshot per user (highest snapshot_id).
            latest: dict[UUID, AnnotationSnapshot] = {}
            for s in all_snaps:
                latest[s.user_id] = s
            snapshots = list(latest.values())
            result = []
            for snap in snapshots:
                user = session.get(User, snap.user_id)
                if user is None:
                    continue
                pointers = list(
                    session.scalars(
                        select(Pointer)
                        .join(
                            SnapshotPointer,
                            (
                                Pointer.reference_id
                                == SnapshotPointer.reference_id
                            )
                            & (Pointer.entity_id == SnapshotPointer.entity_id)
                            & (Pointer.offset == SnapshotPointer.offset)
                            & (Pointer.length == SnapshotPointer.length)
                            & (Pointer.field == SnapshotPointer.field),
                        )
                        .where(SnapshotPointer.snapshot_id == snap.snapshot_id)
                    ).all()
                )
                relation_ids = list(
                    session.scalars(
                        select(SnapshotRelation.relation_id).where(
                            SnapshotRelation.snapshot_id == snap.snapshot_id
                        )
                    ).all()
                )
                relations = (
                    list(
                        session.scalars(
                            select(Relation).where(
                                Relation.relation_id.in_(relation_ids)
                            )
                        ).all()
                    )
                    if relation_ids
                    else []
                )
                result.append(
                    AnnotatorSnapshot(
                        user=user,
                        reference_id=reference_id,
                        pointers=pointers,
                        relations=relations,
                        created_at=snap.created_at,
                    )
                )
            return result

    def save_curated_annotation(
        self,
        project_id: int,
        reference_id: int,
        curator_id: UUID,
        pointers: list[Pointer],
        relations: list[Relation],
    ) -> int:
        """Persist a curator's curated annotation, replacing any previous one.

        :returns: The ``curated_id`` of the stored record.
        """
        content_hash = _content_hash(pointers, relations)
        now = datetime.now(timezone.utc)
        with Session(self.engine) as session:
            existing = session.scalar(
                select(CuratedAnnotation)
                .where(CuratedAnnotation.project_id == project_id)
                .where(CuratedAnnotation.reference_id == reference_id)
                .where(CuratedAnnotation.curator_id == curator_id)
            )
            if existing is not None:
                session.execute(
                    sa_delete(CuratedAnnotationPointer).where(
                        CuratedAnnotationPointer.curated_id
                        == existing.curated_id
                    )
                )
                session.execute(
                    sa_delete(CuratedAnnotationRelation).where(
                        CuratedAnnotationRelation.curated_id
                        == existing.curated_id
                    )
                )
                session.execute(
                    sa_delete(CuratedAnnotation).where(
                        CuratedAnnotation.curated_id == existing.curated_id
                    )
                )
            curated_id: int = session.execute(
                insert(CuratedAnnotation)
                .values(
                    project_id=project_id,
                    reference_id=reference_id,
                    curator_id=curator_id,
                    content_hash=content_hash,
                    created_at=now,
                )
                .returning(CuratedAnnotation.curated_id)
            ).scalar_one()
            for pointer in pointers:
                session.execute(
                    insert(CuratedAnnotationPointer)
                    .values(
                        curated_id=curated_id,
                        reference_id=pointer.reference_id,
                        entity_id=pointer.entity_id,
                        offset=pointer.offset,
                        length=pointer.length,
                        field=pointer.field,
                    )
                    .on_conflict_do_nothing()
                )
            for rel in relations:
                relation_id: int = session.execute(
                    insert(Relation)
                    .values(rel.model_dump(exclude_none=True))
                    .on_conflict_do_update(
                        index_elements=["predicate", "subject", "object"],
                        set_={
                            "predicate": Relation.predicate,
                            "subject": Relation.subject,
                            "object": Relation.object,
                        },
                    )
                    .returning(Relation.relation_id)
                ).scalar_one()
                session.execute(
                    insert(CuratedAnnotationRelation)
                    .values(curated_id=curated_id, relation_id=relation_id)
                    .on_conflict_do_nothing()
                )
            session.commit()
        return curated_id

    def get_curated_annotation(
        self, project_id: int, reference_id: int, curator_id: UUID
    ) -> AnnotatorSnapshot | None:
        """Return a curator's curated annotation as an :class:`AnnotatorSnapshot`,
        or ``None`` if it does not exist yet.
        """
        with Session(self.engine) as session:
            curated = session.scalar(
                select(CuratedAnnotation)
                .where(CuratedAnnotation.project_id == project_id)
                .where(CuratedAnnotation.reference_id == reference_id)
                .where(CuratedAnnotation.curator_id == curator_id)
            )
            if curated is None:
                return None
            curator = session.get(User, curator_id)
            if curator is None:
                return None
            pointers = list(
                session.scalars(
                    select(Pointer)
                    .join(
                        CuratedAnnotationPointer,
                        (
                            Pointer.reference_id
                            == CuratedAnnotationPointer.reference_id
                        )
                        & (
                            Pointer.entity_id
                            == CuratedAnnotationPointer.entity_id
                        )
                        & (Pointer.offset == CuratedAnnotationPointer.offset)
                        & (Pointer.length == CuratedAnnotationPointer.length)
                        & (Pointer.field == CuratedAnnotationPointer.field),
                    )
                    .where(
                        CuratedAnnotationPointer.curated_id
                        == curated.curated_id
                    )
                ).all()
            )
            relation_ids = list(
                session.scalars(
                    select(CuratedAnnotationRelation.relation_id).where(
                        CuratedAnnotationRelation.curated_id
                        == curated.curated_id
                    )
                ).all()
            )
            relations = (
                list(
                    session.scalars(
                        select(Relation).where(
                            Relation.relation_id.in_(relation_ids)
                        )
                    ).all()
                )
                if relation_ids
                else []
            )
            return AnnotatorSnapshot(
                user=curator,
                reference_id=reference_id,
                pointers=pointers,
                relations=relations,
                created_at=curated.created_at,
            )

