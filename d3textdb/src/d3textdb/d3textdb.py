    def delete_ontology(self, ontology_id: int) -> None:
        """Delete an ontology and cascade-remove its entities, names, and triples."""
        with Session(self.engine) as session:
            entity_ids: list[int] = list(
                session.scalars(
                    select(Entity.entity_id).where(
                        Entity.ontology_id == ontology_id
                    )
                )
            )

            if entity_ids:
                session.execute(
                    sa_delete(Triple).where(
                        or_(
                            Triple.subject_id.in_(entity_ids),
                            Triple.object_id.in_(entity_ids),
                        )
                    )
                )

                name_ids: list[int] = list(
                    session.scalars(
                        select(EntityName.name_id).where(
                            EntityName.entity_id.in_(entity_ids)
                        )
                    )
                )

                session.execute(
                    sa_delete(EntityName).where(
                        EntityName.entity_id.in_(entity_ids)
                    )
                )

                if name_ids:
                    still_used = set(
                        session.scalars(
                            select(EntityName.name_id).where(
                                EntityName.name_id.in_(name_ids)
                            )
                        )
                    )
                    orphaned = [n for n in name_ids if n not in still_used]
                    if orphaned:
                        session.execute(
                            sa_delete(Name).where(Name.id.in_(orphaned))
                        )

                session.execute(
                    sa_delete(Entity).where(Entity.entity_id.in_(entity_ids))
                )

            session.execute(
                sa_delete(Ontology).where(Ontology.ontology_id == ontology_id)
            )
            session.commit()

        self.rebuild_fts()

    def set_curation_decision(
        self,
        project_id: int,
        relation_id: int,
        curator_id: UUID,
        verdict: Verdict,
    ) -> None:
        """Upsert a curator's accept/reject verdict on a relation triple."""
        from datetime import datetime, timezone

        with Session(self.engine) as session:
            existing = session.get(
                CurationDecision, (project_id, relation_id, curator_id)
            )
            if existing:
                existing.verdict = verdict
                existing.decided_at = datetime.now(timezone.utc)
            else:
                session.add(
                    CurationDecision(
                        project_id=project_id,
                        relation_id=relation_id,
                        curator_id=curator_id,
                        verdict=verdict,
                        decided_at=datetime.now(timezone.utc),
                    )
                )
            session.commit()

    def get_curation_decisions(
        self, project_id: int, curator_id: UUID
    ) -> dict[int, Verdict]:
        """Return all verdicts a curator has recorded for a project.

        Returns a mapping of relation_id → Verdict.
        """
        with Session(self.engine) as session:
            rows = session.scalars(
                select(CurationDecision).where(
                    CurationDecision.project_id == project_id,
                    CurationDecision.curator_id == curator_id,
                )
            ).all()
        return {row.relation_id: row.verdict for row in rows}
