    def store_items(self, items: Iterable[SQLModel]) -> None:
        """Store ``items`` into the database in accordance to their model class."""
        models: dict = {}
        for item in items:
            models.setdefault(item.__class__, []).append(item)

        with Session(self.engine) as session:
            for item in itertools.chain(
                *(
                    models.get(key, [])
                    for key in (User, Entity, Reference, Pointer)
                )
            ):
                session.execute(
                    insert(item.__class__)
                    .values(item.model_dump(exclude_none=True))
                    .on_conflict_do_nothing()
                )
            session.commit()

