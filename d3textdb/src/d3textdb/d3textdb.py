def hash_password(password: str) -> str:
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode(
        "utf-8"
    )


def _content_hash(pointers: list[Pointer], relations: list[Relation]) -> str:
    """Compute a deterministic SHA-256 hash of the annotation content."""
    pointer_data = sorted(
        (p.entity_id, p.field, p.offset, p.length) for p in pointers
    )
    relation_data = sorted(
        (r.predicate, r.subject, r.object) for r in relations
    )
    payload = json.dumps(
        {"pointers": pointer_data, "relations": relation_data}, sort_keys=True
    )
    return hashlib.sha256(payload.encode()).hexdigest()


class OntologyInUseError(Exception):
    """Raised when an ontology cannot be deleted because annotations exist
    that reference its entities."""


def fts_match_expression(query: str) -> str | None:
    """Build an FTS5 MATCH expression from a free-text query.

    Each token (a maximal run of word characters, matching the unicode61
    tokenizer that backs ``name_fts``) becomes a quoted prefix term
    (``"tok"*``) so partial words match as the user types; tokens are ANDed
    together. Quoting neutralises FTS5 query operators. Returns ``None`` when
    the query contains no usable tokens (e.g. only punctuation), for which the
    caller should treat the search as empty.
    """
    tokens = re.findall(r"\w+", query.lower())
    if not tokens:
        return None
    return " ".join(f'"{tok}"*' for tok in tokens)


class DuplicateCurieError(Exception):
    """Raised when renaming an entity to a CURIE that already exists, which
    would violate the ``entity.curie`` UNIQUE constraint."""


class D3TextDB:
    def __init__(
        self,
        path: os.PathLike | None = None,
        echo: bool = False,  # noqa: FBT001, FBT002
    ) -> None:
        """Initialize the database layer.

        :param path: Location of the database file. If not provided, start an
            in-memory database.
        :param echo: Flag determining whether to output the SQL commands
            generated by SQLAlchemy.
        """
        if path:
            self.engine = create_engine(
                f"sqlite+pysqlite:///{path}", module=pysqlite3, echo=echo
            )
        else:
            self.engine = create_engine(
                "sqlite+pysqlite://",
                echo=echo,
                connect_args={"check_same_thread": False},
                poolclass=StaticPool,
                module=pysqlite3,
            )

        event.listen(
            self.engine,
            "connect",
            lambda dbapi_con, _: dbapi_con.execute("pragma foreign_keys=ON"),
        )
        SQLModel.metadata.create_all(self.engine)
        self._migrate_fk_on_update_cascade()
        self._setup_fts()

    def __del__(self) -> None:
        self.engine.dispose()

    def _setup_fts(self) -> None:
        """Create the FTS5 virtual table and sync triggers for the Name table."""
        with self.engine.begin() as conn:
            conn.execute(
                text(
                    "CREATE VIRTUAL TABLE IF NOT EXISTS name_fts "
                    "USING fts5(label, content='name', content_rowid='id')"
                )
            )
        self._create_fts_triggers()

    def _create_fts_triggers(self) -> None:
        """Create the row-level triggers that keep ``name_fts`` in sync.

        Kept separate from the table creation so the bulk loaders can drop the
        triggers around a large import and rebuild the index once, instead of
        paying per-row trigger cost for millions of rows.
        """
        with self.engine.begin() as conn:
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_ai AFTER INSERT ON name BEGIN "
                    "INSERT INTO name_fts(rowid, label) VALUES (new.id, new.label); "
                    "END"
                )
            )
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_au AFTER UPDATE ON name BEGIN "
                    "INSERT INTO name_fts(name_fts, rowid, label) VALUES ('delete', old.id, old.label); "
                    "INSERT INTO name_fts(rowid, label) VALUES (new.id, new.label); "
                    "END"
                )
            )
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_ad AFTER DELETE ON name BEGIN "
                    "INSERT INTO name_fts(name_fts, rowid, label) VALUES ('delete', old.id, old.label); "
                    "END"
                )
            )

    def _drop_fts_triggers(self) -> None:
        """Drop the ``name_fts`` sync triggers (paired with a later rebuild)."""
        with self.engine.begin() as conn:
            for trig in ("name_ai", "name_au", "name_ad"):
                conn.execute(text(f"DROP TRIGGER IF EXISTS {trig}"))

    @contextmanager
    def _fts_bulk_reindex(self):
        """Suppress the per-row FTS triggers for a bulk write, rebuild once after.

        Drops the sync triggers on entry so a large import/delete doesn't pay
        per-row trigger cost, then on exit (even on error) recreates them and
        rebuilds ``name_fts`` from the Name table so the index reflects whatever
        was committed. Triggers are recreated *before* the rebuild so a
        concurrent single-row write during the rebuild is still indexed.
        """
        self._drop_fts_triggers()
        try:
            yield
        finally:
            self._create_fts_triggers()
            self.rebuild_fts()

    def _migrate_fk_on_update_cascade(self) -> None:
        """Rebuild tables whose ``entity.curie`` FK predates ON UPDATE CASCADE.

        Older databases were created with SQLite's default (NO ACTION), which
        forced curie renames to disable FK enforcement. Rebuild those tables so
        a rename cascades with enforcement left on. Idempotent: a no-op once the
        FKs already cascade, so it costs one PRAGMA read per startup on
        already-migrated (and freshly created) databases.
        """
        for table in ("pointer", "relation"):
            if self._entity_fk_needs_cascade(table):
                self._rebuild_table_from_metadata(table)

    def _entity_fk_needs_cascade(self, table: str) -> bool:
        with self.engine.connect() as conn:
            rows = conn.exec_driver_sql(
                f"PRAGMA foreign_key_list('{table}')"
            ).fetchall()
        # PRAGMA columns: id, seq, table, from, to, on_update, on_delete, match
        entity_fks = [row for row in rows if row[2] == "entity"]
        return any(row[5] != "CASCADE" for row in entity_fks)

    def _rebuild_table_from_metadata(self, table: str) -> None:
        """Recreate ``table`` from the current SQLModel definition, copying rows.

        SQLite cannot ALTER a foreign key's action, so the only way to change it
        on an existing table is the standard rebuild (rename → create → copy →
        drop). This runs on the raw DBAPI connection in autocommit mode
        (``isolation_level = None``) so an explicit BEGIN/COMMIT makes the whole
        rebuild atomic — pysqlite otherwise issues an implicit COMMIT before
        each DDL statement, which would break a SQLAlchemy transaction. ``PRAGMA
        foreign_keys`` is toggled here too, since SQLite ignores it mid-transaction.
        """
        md_table = SQLModel.metadata.tables[table]
        columns = ", ".join(f'"{col.name}"' for col in md_table.columns)
        create_sql = str(CreateTable(md_table).compile(self.engine))
        raw = self.engine.raw_connection()
        try:
            dbapi = raw.dbapi_connection
            prior_isolation = dbapi.isolation_level
            dbapi.isolation_level = None
            cursor = dbapi.cursor()
            cursor.execute("PRAGMA foreign_keys = OFF")
            # Other tables (state_pointer, snapshot_pointer, …) hold FKs to the
            # table being rebuilt. legacy_alter_table=ON stops the RENAME from
            # rewriting those references to the temp name and leaving them
            # dangling.
            cursor.execute("PRAGMA legacy_alter_table = ON")
            cursor.execute("BEGIN")
            try:
                cursor.execute(
                    f'ALTER TABLE "{table}" RENAME TO "{table}__old"'
                )
                cursor.execute(create_sql)
                cursor.execute(
                    f'INSERT INTO "{table}" ({columns}) '
                    f'SELECT {columns} FROM "{table}__old"'
                )
                cursor.execute(f'DROP TABLE "{table}__old"')
                violations = cursor.execute(
                    "PRAGMA foreign_key_check"
                ).fetchall()
                if violations:
                    raise RuntimeError(
                        f"foreign_key_check failed after rebuilding "
                        f"{table!r}: {violations}"
                    )
                cursor.execute("COMMIT")
            except BaseException:
                cursor.execute("ROLLBACK")
                raise
            finally:
                cursor.execute("PRAGMA legacy_alter_table = OFF")
                cursor.execute("PRAGMA foreign_keys = ON")
                cursor.close()
                dbapi.isolation_level = prior_isolation
        finally:
            raw.close()

