def hash_password(password: str) -> str:
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode(
        "utf-8"
    )


def _content_hash(pointers: list[Pointer], relations: list[Relation]) -> str:
    """Compute a deterministic SHA-256 hash of the annotation content."""
    pointer_data = sorted((p.entity_id, p.field, p.offset, p.length) for p in pointers)
    relation_data = sorted(
        (r.predicate, r.subject, r.object) for r in relations
    )
    payload = json.dumps(
        {"pointers": pointer_data, "relations": relation_data}, sort_keys=True
    )
    return hashlib.sha256(payload.encode()).hexdigest()


class D3TextDB:
    def __init__(
        self,
        path: os.PathLike | None = None,
        echo: bool = False,  # noqa: FBT001, FBT002
    ) -> None:
        """Initialize the database layer.

        :param path: Location of the database file. If not provided, start an
            in-memory database.
        :param echo: Flag determining whether to output the SQL commands
            generated by SQLAlchemy.
        """
        if path:
            self.engine = create_engine(f"sqlite:///{path}", echo=echo)
        else:
            self.engine = create_engine(
                "sqlite://",
                echo=echo,
                connect_args={"check_same_thread": False},
                poolclass=StaticPool,
            )

        event.listen(
            self.engine,
            "connect",
            lambda dbapi_con, _: dbapi_con.execute("pragma foreign_keys=ON"),
        )
        SQLModel.metadata.create_all(self.engine)
        self._setup_fts()

    def __del__(self) -> None:
        self.engine.dispose()

    def _setup_fts(self) -> None:
        """Create the FTS5 virtual table and sync triggers for the Name table."""
        with self.engine.begin() as conn:
            conn.execute(
                text(
                    "CREATE VIRTUAL TABLE IF NOT EXISTS name_fts "
                    "USING fts5(label, content='name', content_rowid='id')"
                )
            )
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_ai AFTER INSERT ON name BEGIN "
                    "INSERT INTO name_fts(rowid, label) VALUES (new.id, new.label); "
                    "END"
                )
            )
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_au AFTER UPDATE ON name BEGIN "
                    "INSERT INTO name_fts(name_fts, rowid, label) VALUES ('delete', old.id, old.label); "
                    "INSERT INTO name_fts(rowid, label) VALUES (new.id, new.label); "
                    "END"
                )
            )
            conn.execute(
                text(
                    "CREATE TRIGGER IF NOT EXISTS name_ad AFTER DELETE ON name BEGIN "
                    "INSERT INTO name_fts(name_fts, rowid, label) VALUES ('delete', old.id, old.label); "
                    "END"
                )
            )

    def search_entities(
        self,
        query: str,
        limit: int = 20,
        project_id: int | None = None,
        is_class: bool = False,
    ) -> list[EntityAnnotation]:
        """Search entities by name/synonym using a prefix LIKE match.

        If `is_class` is True, only OWL classes are returned (for class pickers).
        If False (default), only non-class individuals are returned (for annotation search).
        If `project_id` is given, results include:
          - confirmed entities whose ontology is assigned to that project, AND
          - unconfirmed (proposed) entities that belong to that project.
        """
        if not query.strip():
            return []

        pref_en = aliased(EntityName)
        pref_name = aliased(Name)
        match_name = aliased(Name)

        pattern = f"{query.strip()}%"

        stmt = (
            select(
                Entity.curie,
                Entity.type,
                Entity.confirmed,
                pref_name.label.label("preferred_name"),
                func.min(func.length(match_name.label)).label("best_len"),
            )
            .join(EntityName, EntityName.entity_id == Entity.entity_id)
            .join(match_name, match_name.id == EntityName.name_id)
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
            .where(match_name.label.ilike(pattern))
            .where(Entity.is_class == is_class)
            .group_by(Entity.curie, Entity.type, Entity.confirmed, pref_name.label)
            .order_by(func.min(func.length(match_name.label)))
            .limit(limit)
        )

        if project_id is not None:
            stmt = stmt.outerjoin(
                ProjectOntology,
                (ProjectOntology.ontology_id == Entity.ontology_id)
                & (ProjectOntology.project_id == project_id),
            ).where(
                # confirmed entity in one of the project's ontologies
                (ProjectOntology.project_id == project_id)
                # OR proposed entity belonging to this project
                | ((Entity.confirmed == False) & (Entity.project_id == project_id))  # noqa: E712
            )

        with Session(self.engine) as session:
            rows = session.execute(stmt).fetchall()

        return [
            EntityAnnotation(
                entity_id=row.curie,
                preferred_name=row.preferred_name or "",
                kind=row.type,
                confirmed=row.confirmed,
            )
            for row in rows
        ]

    def get_entities_by_curies(self, curies: list[str]) -> list[EntityAnnotation]:
        """Return EntityAnnotation objects for the given CURIE list.

        Entities not found in the database are silently omitted.
        """
        if not curies:
            return []
        pref_en = aliased(EntityName)
        pref_name = aliased(Name)
        stmt = (
            select(
                Entity.curie,
                Entity.type,
                Entity.confirmed,
                pref_name.label.label("preferred_name"),
            )
            .where(Entity.curie.in_(curies))
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
        )
        with Session(self.engine) as session:
            rows = session.execute(stmt).fetchall()
        return [
            EntityAnnotation(
                entity_id=row.curie,
                preferred_name=row.preferred_name or row.curie,
                kind=row.type,
                confirmed=row.confirmed,
            )
            for row in rows
        ]

    def list_proposed_entities(
        self,
        project_id: int,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[list[dict], int]:
        """Return proposed entities for a project, newest first."""
        pref_en = aliased(EntityName)
        pref_name = aliased(Name)

        base_where = (
            (Entity.confirmed == False)  # noqa: E712
            & (Entity.project_id == project_id)
        )
        stmt = (
            select(
                Entity.entity_id,
                Entity.curie,
                Entity.type,
                Entity.proposed_by,
                Entity.proposal_status,
                Entity.proposed_at,
                pref_name.label.label("preferred_name"),
            )
            .outerjoin(pref_en, (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred)
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
            .where(base_where)
        )

        with Session(self.engine) as session:
            total = session.execute(
                select(func.count())
                .select_from(Entity)
                .where(base_where)
            ).scalar_one()

            rows = session.execute(
                stmt.order_by(Entity.proposed_at.desc())
                .limit(limit)
                .offset(offset)
            ).fetchall()

        return [
            {
                "proposal_id": r.entity_id,
                "curie": r.curie,
                "label": r.preferred_name or r.curie,
                "kind": r.type,
                "proposed_by": r.proposed_by,
                "status": r.proposal_status,
                "created_at": r.proposed_at.isoformat() if r.proposed_at else None,
            }
            for r in rows
        ], total

    def store_proposed_entity(
        self,
        project_id: int,
        label: str,
        curie: str,
        kind: str,
        proposed_by: str | None = None,
    ) -> dict:
        """Insert a new proposed entity into the entity table and return it as a dict."""
        now = datetime.now(timezone.utc)
        with Session(self.engine) as session:
            row = Entity(
                curie=curie,
                type=kind,
                confirmed=False,
                project_id=project_id,
                proposed_by=proposed_by,
                proposal_status="pending",
                proposed_at=now,
            )
            session.add(row)
            session.commit()
            session.refresh(row)
            return {
                "proposal_id": row.entity_id,
                "curie": row.curie,
                "label": label,
                "kind": row.type,
                "proposed_by": row.proposed_by,
                "status": row.proposal_status,
                "created_at": row.proposed_at.isoformat() if row.proposed_at else None,
            }

    def list_proposed_properties(
        self,
        project_id: int,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[list[dict], int]:
        """Return proposed properties for a project, newest first."""
        with Session(self.engine) as session:
            total = session.execute(
                select(func.count())
                .select_from(ProposedProperty)
                .where(ProposedProperty.project_id == project_id)
            ).scalar_one()

            rows = session.execute(
                select(ProposedProperty)
                .where(ProposedProperty.project_id == project_id)
                .order_by(ProposedProperty.created_at.desc())
                .limit(limit)
                .offset(offset)
            ).scalars().all()

        return [
            {
                "proposal_id": r.proposal_id,
                "curie": r.curie,
                "label": r.label,
                "domain_curie": r.domain_curie,
                "range_curie": r.range_curie,
                "proposed_by": r.proposed_by,
                "status": r.status,
                "created_at": r.created_at.isoformat(),
            }
            for r in rows
        ], total

