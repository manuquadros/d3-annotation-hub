    def get_reference_annotation(
        self, pubmed_id: int, user_id: UUID, project_id: int
    ) -> ReferenceAnnotation:
        """Retrieve reference annotation from the database.

        Returns the annotation corresponding to the latest AnnotationState for
        the given (project, user, reference) triple. ``completed`` is True when
        the latest state's content hash matches the most recent
        AnnotationSnapshot for the same triple.

        :param pubmed_id: PubMed id to retrieve with annotations from the db.
        :param user_id: User id to retrieve annotations for.
        :param project_id: Project the annotation belongs to.
        :return: ReferenceAnnotation model for ``pubmed_id`` and ``user_id``.
        :raises ValueError: If reference or user not found.
        """
        with Session(self.engine) as session:
            reference = session.scalar(
                select(Reference).where(Reference.pubmed_id == pubmed_id)
            )
            if reference is None:
                raise ValueError(
                    f"Reference with pubmed_id {pubmed_id} not found"
                )

            user = session.get(User, user_id)
            if user is None:
                raise ValueError(f"User with user_id {user_id} not found")

            # Latest state for this (project, user, reference) triple.
            latest_state = session.scalar(
                select(AnnotationState)
                .where(AnnotationState.project_id == project_id)
                .where(AnnotationState.user_id == user_id)
                .where(AnnotationState.reference_id == reference.reference_id)
                .order_by(AnnotationState.state_id.desc())
                .limit(1)
            )

            if latest_state is None:
                return ReferenceAnnotation(
                    project_id=project_id,
                    user=User.model_validate(user),
                    reference=Reference.model_validate(reference),
                    pointers=[],
                    relations=[],
                    completed=False,
                    last_updated=datetime.now(timezone.utc),
                )

            # Load pointers via JOIN with StatePointer.
            pointers = list(
                session.scalars(
                    select(Pointer)
                    .join(
                        StatePointer,
                        (Pointer.reference_id == StatePointer.reference_id)
                        & (Pointer.entity_id == StatePointer.entity_id)
                        & (Pointer.offset == StatePointer.offset)
                        & (Pointer.length == StatePointer.length)
                        & (Pointer.field == StatePointer.field),
                    )
                    .where(StatePointer.state_id == latest_state.state_id)
                )
            )

            # Load the entities referenced by those pointers.
            # Pointer.entity_id stores the CURIE; Entity is looked up by curie.
            entity_curies = {p.entity_id for p in pointers}
            entities: list[EntityAnnotation] = []
            if entity_curies:
                rows = list(
                    session.scalars(
                        select(Entity).where(Entity.curie.in_(entity_curies))
                    )
                )
                for entity in rows:
                    # Preferred name: EntityName row with is_preferred=True.
                    preferred_name = (
                        session.scalar(
                            select(Name.label)
                            .join(EntityName, Name.id == EntityName.name_id)
                            .where(EntityName.entity_id == entity.entity_id)
                            .where(EntityName.is_preferred.is_(True))
                        )
                        or ""
                    )

                    # Synonyms: all other EntityName rows.
                    synonyms = list(
                        session.scalars(
                            select(Name.label)
                            .join(EntityName, Name.id == EntityName.name_id)
                            .where(EntityName.entity_id == entity.entity_id)
                            .where(EntityName.is_preferred.is_(False))
                        )
                    )
                    entities.append(
                        EntityAnnotation(
                            entity_id=entity.curie,
                            preferred_name=preferred_name,
                            kind=entity.type,
                            synonyms=synonyms,
                            confirmed=entity.confirmed,
                            is_class=entity.is_class,
                        )
                    )

            # Load relations via JOIN with StateRelation.
            relations = list(
                session.scalars(
                    select(Relation)
                    .join(
                        StateRelation,
                        Relation.relation_id == StateRelation.relation_id,
                    )
                    .where(StateRelation.state_id == latest_state.state_id)
                )
            )

            # Completed when the latest snapshot for this (project, user,
            # reference) triple has the same content hash.
            latest_snapshot = session.scalar(
                select(AnnotationSnapshot)
                .where(AnnotationSnapshot.project_id == project_id)
                .where(AnnotationSnapshot.user_id == user_id)
                .where(
                    AnnotationSnapshot.reference_id == reference.reference_id
                )
                .order_by(AnnotationSnapshot.snapshot_id.desc())
                .limit(1)
            )
            completed = (
                latest_snapshot is not None
                and latest_snapshot.content_hash == latest_state.content_hash
            )

            return ReferenceAnnotation(
                project_id=project_id,
                user=User.model_validate(user),
                reference=Reference.model_validate(reference),
                entities=entities,
                pointers=pointers,
                relations=relations,
                completed=completed,
                last_updated=latest_state.recorded_at,
            )

