    def search_entities(
        self,
        query: str,
        limit: int = 20,
        project_id: int | None = None,
        is_class: bool = False,
    ) -> list[EntityAnnotation]:
        """Search entities by name/synonym through the ``name_fts`` FTS5 index.

        The query is tokenised into per-word prefix terms, so ``coli`` matches
        the ``coli`` token in "Escherichia coli". Candidate names are found via
        the index (``MATCH``) rather than a full-table ``LIKE '%…%'`` scan.

        Results are ranked: preferred-name exact match → preferred-name prefix
        match → preferred-name contains match → synonym-only match. Within each
        tier, entities whose names prefix-match rank above contains-only matches,
        then by shortest matching name length.

        If `is_class` is True, only OWL classes are returned (for class pickers).
        If False (default), only non-class individuals are returned (for annotation search).
        If `project_id` is given, results include:
          - confirmed entities whose ontology is assigned to that project, AND
          - unconfirmed (proposed) entities that belong to that project.
        """
        q = query.strip()
        match_expr = fts_match_expression(q)
        if match_expr is None:
            return []

        pref_en = aliased(EntityName)
        pref_name = aliased(Name)
        match_name = aliased(Name)

        prefix_pattern = f"{q}%"
        contains_pattern = f"%{q}%"

        name_fts = sa_table("name_fts", column("rowid"))
        fts_ids = select(name_fts.c.rowid).where(
            text("name_fts MATCH :fts_q").bindparams(fts_q=match_expr)
        )

        preferred_match_tier = func.max(
            case(
                (func.lower(pref_name.label) == q.lower(), 0),
                (pref_name.label.ilike(prefix_pattern), 1),
                (pref_name.label.ilike(contains_pattern), 2),
                else_=3,
            )
        )

        any_name_prefix = func.min(
            case((match_name.label.ilike(prefix_pattern), 0), else_=1)
        )

        stmt = (
            select(
                Entity.curie,
                Entity.type,
                Entity.confirmed,
                func.max(pref_name.label).label(
                    "preferred_name"
                ),  # MAX collapses the group; each entity has one preferred name
                func.min(func.length(match_name.label)).label("best_len"),
            )
            .join(EntityName, EntityName.entity_id == Entity.entity_id)
            .join(match_name, match_name.id == EntityName.name_id)
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
            .where(match_name.id.in_(fts_ids))
            .where(Entity.is_class == is_class)
            .group_by(Entity.curie, Entity.type, Entity.confirmed)
            .order_by(
                preferred_match_tier,
                any_name_prefix,
                func.min(func.length(match_name.label)),
            )
            .limit(limit)
        )

        if project_id is not None:
            stmt = stmt.outerjoin(
                ProjectOntology,
                (ProjectOntology.ontology_id == Entity.ontology_id)
                & (ProjectOntology.project_id == project_id),
            ).where(
                # confirmed entity in one of the project's ontologies
                (ProjectOntology.project_id == project_id)
                # OR proposed entity belonging to this project
                | (
                    (Entity.confirmed == False)
                    & (Entity.project_id == project_id)
                )  # noqa: E712
            )

        with Session(self.engine) as session:
            rows = session.execute(stmt).fetchall()

        return [
            EntityAnnotation(
                entity_id=row.curie,
                preferred_name=row.preferred_name or "",
                kind=row.type,
                confirmed=row.confirmed,
            )
            for row in rows
        ]

    def get_entities_by_curies(
        self, curies: list[str]
    ) -> list[EntityAnnotation]:
        """Return EntityAnnotation objects for the given CURIE list.

        Entities not found in the database are silently omitted.
        """
        if not curies:
            return []
        pref_en = aliased(EntityName)
        pref_name = aliased(Name)
        stmt = (
            select(
                Entity.curie,
                Entity.type,
                Entity.confirmed,
                pref_name.label.label("preferred_name"),
            )
            .where(Entity.curie.in_(curies))
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
        )
        with Session(self.engine) as session:
            rows = session.execute(stmt).fetchall()
        return [
            EntityAnnotation(
                entity_id=row.curie,
                preferred_name=row.preferred_name or row.curie,
                kind=row.type,
                confirmed=row.confirmed,
            )
            for row in rows
        ]

    def list_proposed_entities(
        self,
        project_id: int,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[list[dict], int]:
        """Return proposed entities for a project, newest first."""
        pref_en = aliased(EntityName)
        pref_name = aliased(Name)

        base_where = (
            (Entity.confirmed == False)  # noqa: E712
            & (Entity.project_id == project_id)
        )
        stmt = (
            select(
                Entity.entity_id,
                Entity.curie,
                Entity.type,
                Entity.proposed_by,
                Entity.proposal_status,
                Entity.proposed_at,
                pref_name.label.label("preferred_name"),
            )
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
            .where(base_where)
        )

        with Session(self.engine) as session:
            total = session.execute(
                select(func.count()).select_from(Entity).where(base_where)
            ).scalar_one()

            rows = session.execute(
                stmt.order_by(Entity.proposed_at.desc())
                .limit(limit)
                .offset(offset)
            ).fetchall()

        return [
            {
                "proposal_id": r.entity_id,
                "curie": r.curie,
                "label": r.preferred_name or r.curie,
                "kind": r.type,
                "proposed_by": r.proposed_by,
                "status": r.proposal_status,
                "created_at": r.proposed_at.isoformat()
                if r.proposed_at
                else None,
            }
            for r in rows
        ], total

    def store_proposed_entity(
        self,
        project_id: int,
        label: str,
        curie: str,
        kind: str,
        proposed_by: str | None = None,
    ) -> dict:
        """Insert a new proposed entity into the entity table and return it as a dict.

        Raises DuplicateCurieError if ``curie`` already exists (``entity.curie``
        is UNIQUE), so the caller can map it to a 409 rather than a 500.
        """
        now = datetime.now(timezone.utc)
        with Session(self.engine) as session:
            row = Entity(
                curie=curie,
                type=kind,
                confirmed=False,
                project_id=project_id,
                proposed_by=proposed_by,
                proposal_status="pending",
                proposed_at=now,
            )
            session.add(row)
            try:
                session.commit()
            except IntegrityError as exc:
                raise DuplicateCurieError(
                    f"CURIE '{curie}' is already in use"
                ) from exc
            session.refresh(row)
            return {
                "proposal_id": row.entity_id,
                "curie": row.curie,
                "label": label,
                "kind": row.type,
                "proposed_by": row.proposed_by,
                "status": row.proposal_status,
                "created_at": row.proposed_at.isoformat()
                if row.proposed_at
                else None,
            }

    def list_proposed_properties(
        self,
        project_id: int,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[list[dict], int]:
        """Return proposed properties for a project, newest first."""
        with Session(self.engine) as session:
            total = session.execute(
                select(func.count())
                .select_from(ProposedProperty)
                .where(ProposedProperty.project_id == project_id)
            ).scalar_one()

            rows = (
                session.execute(
                    select(ProposedProperty)
                    .where(ProposedProperty.project_id == project_id)
                    .order_by(ProposedProperty.created_at.desc())
                    .limit(limit)
                    .offset(offset)
                )
                .scalars()
                .all()
            )

        return [
            {
                "proposal_id": r.proposal_id,
                "curie": r.curie,
                "label": r.label,
                "domain_curie": r.domain_curie,
                "range_curie": r.range_curie,
                "proposed_by": r.proposed_by,
                "status": r.status,
                "created_at": r.created_at.isoformat(),
            }
            for r in rows
        ], total

