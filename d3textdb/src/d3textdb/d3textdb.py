    def confirm_entity(self, curie: str) -> None:
        """Promote a proposed entity: set confirmed=True and clear proposal metadata."""
        with Session(self.engine) as session:
            entity = session.scalars(
                select(Entity).where(Entity.curie == curie)
            ).first()
            if entity:
                entity.confirmed = True
                entity.proposal_status = "accepted"
                entity.project_id = None
                session.add(entity)
                session.commit()

    def delete_entity(self, curie: str) -> None:
        """Delete a proposed entity and all referencing rows."""
        with Session(self.engine) as session:
            entity = session.scalars(
                select(Entity).where(Entity.curie == curie)
            ).first()
            if not entity:
                return

            entity_int_id = entity.entity_id

            # Collect relation_ids that reference this entity
            rel_ids: list[int] = list(
                session.scalars(
                    select(Relation.relation_id).where(
                        or_(Relation.subject == curie, Relation.object == curie)
                    )
                )
            )

            # Delete association rows for those relations
            if rel_ids:
                session.execute(
                    sa_delete(StateRelation).where(
                        StateRelation.relation_id.in_(rel_ids)
                    )
                )
                session.execute(
                    sa_delete(SnapshotRelation).where(
                        SnapshotRelation.relation_id.in_(rel_ids)
                    )
                )
                session.execute(
                    sa_delete(UserRelationReference).where(
                        UserRelationReference.relation_id.in_(rel_ids)
                    )
                )
                session.execute(
                    sa_delete(Relation).where(Relation.relation_id.in_(rel_ids))
                )

            # Delete pointer association rows then pointers
            session.execute(
                sa_delete(StatePointer).where(StatePointer.entity_id == curie)
            )
            session.execute(
                sa_delete(SnapshotPointer).where(
                    SnapshotPointer.entity_id == curie
                )
            )
            session.execute(
                sa_delete(Pointer).where(Pointer.entity_id == curie)
            )

            # Delete entity names (collect name_ids first for orphan cleanup)
            name_ids: list[int] = list(
                session.scalars(
                    select(EntityName.name_id).where(
                        EntityName.entity_id == entity_int_id
                    )
                )
            )
            session.execute(
                sa_delete(EntityName).where(
                    EntityName.entity_id == entity_int_id
                )
            )
            if name_ids:
                still_used = set(
                    session.scalars(
                        select(EntityName.name_id).where(
                            EntityName.name_id.in_(name_ids)
                        )
                    )
                )
                orphaned = [n for n in name_ids if n not in still_used]
                if orphaned:
                    session.execute(
                        sa_delete(Name).where(Name.id.in_(orphaned))
                    )

            session.execute(
                sa_delete(Entity).where(Entity.entity_id == entity_int_id)
            )
            session.commit()

        self.rebuild_fts()

    def update_entity_curie(self, old_curie: str, new_curie: str) -> None:
        """Rename an entity's CURIE, updating all FK-referencing tables."""
        with Session(self.engine) as session:
            # Disable FK checks for the duration of the rename
            session.execute(text("PRAGMA foreign_keys = OFF"))
            session.execute(
                text("UPDATE entity SET curie = :new WHERE curie = :old"),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(
                text(
                    "UPDATE pointer SET entity_id = :new WHERE entity_id = :old"
                ),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(
                text(
                    "UPDATE state_pointer SET entity_id = :new WHERE entity_id = :old"
                ),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(
                text(
                    "UPDATE snapshot_pointer SET entity_id = :new WHERE entity_id = :old"
                ),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(
                text("UPDATE relation SET subject = :new WHERE subject = :old"),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(
                text("UPDATE relation SET object = :new WHERE object = :old"),
                {"new": new_curie, "old": old_curie},
            )
            session.execute(text("PRAGMA foreign_keys = ON"))
            session.commit()

    def store_annotation(self, ann: ReferenceAnnotation) -> None:
        """Persist an annotation state to the database.

        Stores the reference, pointers (entities must already exist), relations,
        and records a new AnnotationState with associated StatePointer /
        StateRelation rows. If ``ann.completed`` is True an AnnotationSnapshot
        is also recorded.
        """
        reference_id = self.store_reference(ann.reference)

        for pointer in ann.pointers:
            pointer.reference_id = reference_id

        content_hash = _content_hash(ann.pointers, ann.relations)
        now = datetime.now(timezone.utc)

        with Session(self.engine, autoflush=False) as session:
            # Upsert entities before inserting pointers.
            for entity in ann.entities:
                if not entity.confirmed:
                    # Proposed (annotator-coined) entities live in the entity table
                    # with confirmed=False and project-scoping metadata.
                    # on_conflict_do_update with a no-op set lets us always get the
                    # entity_id back (needed to link Name rows), while leaving existing
                    # rows unchanged on re-save.
                    int_entity_id = session.execute(
                        insert(Entity)
                        .values(
                            curie=entity.entity_id,
                            type=entity.kind,
                            confirmed=False,
                            project_id=ann.project_id,
                            proposal_status="pending",
                            proposed_at=now,
                        )
                        .on_conflict_do_update(
                            index_elements=["curie"],
                            set_={"type": Entity.type},  # no-op; keeps existing row
                        )
                        .returning(Entity.entity_id)
                    ).scalar_one()

                    # Store preferred_name so the entity is searchable and the
                    # admin listing has a meaningful label.
                    trimmed = entity.preferred_name.strip()
                    if trimmed:
                        name_id = session.execute(
                            insert(Name)
                            .values(label=trimmed)
                            .on_conflict_do_update(
                                index_elements=["label"],
                                set_={"label": Name.label},
                            )
                            .returning(Name.id)
                        ).scalar_one()
                        session.execute(
                            insert(EntityName)
                            .values(
                                entity_id=int_entity_id,
                                name_id=name_id,
                                is_preferred=True,
                            )
                            .on_conflict_do_update(
                                index_elements=["entity_id", "name_id"],
                                set_={"is_preferred": True},
                            )
                        )
                    continue

                # Confirmed (ontology) entity — upsert into entity table.
                int_entity_id = session.execute(
                    insert(Entity)
                    .values(
                        curie=entity.entity_id,
                        type=entity.kind,
                        confirmed=True,
                    )
                    .on_conflict_do_update(
                        index_elements=["curie"],
                        set_={"type": Entity.type},  # confirmed intentionally omitted
                    )
                    .returning(Entity.entity_id)
                ).scalar_one()

                # Upsert all names (preferred + synonyms) into Name table,
                # then link via EntityName.
                # Exclude any synonym equal to the preferred name so the
                # preferred flag is never overwritten to False.
                all_names = [(entity.preferred_name, True)] + [
                    (s, False)
                    for s in entity.synonyms
                    if s != entity.preferred_name
                ]
                for label, is_preferred in all_names:
                    name_id = session.execute(
                        insert(Name)
                        .values(label=label)
                        .on_conflict_do_update(
                            index_elements=["label"],
                            set_={"label": Name.label},
                        )
                        .returning(Name.id)
                    ).scalar_one()
                    session.execute(
                        insert(EntityName)
                        .values(
                            entity_id=int_entity_id,
                            name_id=name_id,
                            is_preferred=is_preferred,
                        )
                        .on_conflict_do_update(
                            index_elements=["entity_id", "name_id"],
                            set_={"is_preferred": is_preferred},
                        )
                    )

            session.flush()

            # Store pointers.
            for pointer in ann.pointers:
                session.execute(
                    insert(Pointer)
                    .values(
                        reference_id=pointer.reference_id,
                        entity_id=pointer.entity_id,
                        offset=pointer.offset,
                        length=pointer.length,
                        field=pointer.field,
                        exact_text=pointer.exact_text,
                        prefix_text=pointer.prefix_text,
                        suffix_text=pointer.suffix_text,
                    )
                    .on_conflict_do_update(
                        index_elements=["reference_id", "entity_id", "offset", "length", "field"],
                        set_={
                            "exact_text": pointer.exact_text,
                            "prefix_text": pointer.prefix_text,
                            "suffix_text": pointer.suffix_text,
                        },
                    )
                )

            session.flush()

            # Store relations and UserRelationReference entries.
            relation_ids: list[int] = []
            for relmodel in ann.relations:
                relation_id = session.execute(
                    insert(Relation)
                    .values(relmodel.model_dump(exclude_none=True))
                    .on_conflict_do_update(
                        index_elements=["predicate", "subject", "object"],
                        set_={
                            "predicate": Relation.predicate,
                            "subject": Relation.subject,
                            "object": Relation.object,
                        },
                    )
                    .returning(Relation.relation_id)
                ).scalar_one()
                relation_ids.append(relation_id)
                session.execute(
                    insert(UserRelationReference)
                    .values(
                        UserRelationReference(
                            user_id=ann.user.user_id,
                            reference_id=reference_id,
                            relation_id=relation_id,
                        ).model_dump()
                    )
                    .on_conflict_do_nothing()
                )

            # Record the annotation state.
            state_id = session.execute(
                insert(AnnotationState)
                .values(
                    project_id=ann.project_id,
                    user_id=ann.user.user_id,
                    reference_id=reference_id,
                    content_hash=content_hash,
                    recorded_at=now,
                )
                .returning(AnnotationState.state_id)
            ).scalar_one()

            for pointer in ann.pointers:
                session.execute(
                    insert(StatePointer)
                    .values(
                        state_id=state_id,
                        reference_id=pointer.reference_id,
                        entity_id=pointer.entity_id,
                        offset=pointer.offset,
                        length=pointer.length,
                        field=pointer.field,
                    )
                    .on_conflict_do_nothing()
                )

            for relation_id in relation_ids:
                session.execute(
                    insert(StateRelation)
                    .values(state_id=state_id, relation_id=relation_id)
                    .on_conflict_do_nothing()
                )

            # Optionally record an immutable snapshot.
            if ann.completed:
                snapshot_id = session.execute(
                    insert(AnnotationSnapshot)
                    .values(
                        project_id=ann.project_id,
                        user_id=ann.user.user_id,
                        reference_id=reference_id,
                        content_hash=content_hash,
                        created_at=now,
                    )
                    .returning(AnnotationSnapshot.snapshot_id)
                ).scalar_one()

                for pointer in ann.pointers:
                    session.execute(
                        insert(SnapshotPointer)
                        .values(
                            snapshot_id=snapshot_id,
                            reference_id=pointer.reference_id,
                            entity_id=pointer.entity_id,
                            offset=pointer.offset,
                            length=pointer.length,
                            field=pointer.field,
                        )
                        .on_conflict_do_nothing()
                    )

                for relation_id in relation_ids:
                    session.execute(
                        insert(SnapshotRelation)
                        .values(
                            snapshot_id=snapshot_id, relation_id=relation_id
                        )
                        .on_conflict_do_nothing()
                    )

            session.commit()

    def store_reference(self, reference: Reference) -> int:
        """Store reference and return its primary key.

        Upserts by pubmed_id when set, else by doi when set, else plain insert.
        reference_id is always excluded from the INSERT so that the DB
        auto-assigns a fresh PK for new rows; existing rows are matched on the
        natural identifier and left otherwise unchanged.
        """
        data = reference.model_dump(exclude={"reference_id"}, exclude_none=True)

        if reference.pubmed_id is not None:
            conflict_target = ["pubmed_id"]
        elif reference.doi is not None:
            conflict_target = ["doi"]
        else:
            conflict_target = None

        with Session(self.engine) as session:
            if conflict_target:
                stmt = (
                    insert(Reference)
                    .values(data)
                    .on_conflict_do_update(
                        index_elements=conflict_target,
                        set_={conflict_target[0]: data[conflict_target[0]]},
                    )
                    .returning(Reference.reference_id)
                )
            else:
                stmt = insert(Reference).values(data).returning(Reference.reference_id)

            ref_id: int = session.scalar(stmt)
            session.commit()

        return ref_id

