    def load_ontology_entities(
        self,
        ontology_id: int,
        entities: Iterable[EntityAnnotation],
        batch_size: int = 500,
    ) -> int:
        """Bulk-load entities from an ontology into the database.

        Each entity's ``entity_id`` field is treated as the CURIE. Names and
        synonyms are upserted into the ``Name`` / ``EntityName`` tables.

        Rows are committed in batches of ``batch_size`` for memory efficiency.
        The FTS5 sync triggers are suppressed for the duration and the index is
        rebuilt once at the end, which is much faster than paying per-row trigger
        cost for large ontologies.

        Returns the total number of entities processed.
        """
        total = 0
        batch: list[EntityAnnotation] = []
        with self._fts_bulk_reindex():
            for entity in entities:
                batch.append(entity)
                if len(batch) >= batch_size:
                    self._load_entity_batch(ontology_id, batch)
                    total += len(batch)
                    batch = []
            if batch:
                self._load_entity_batch(ontology_id, batch)
                total += len(batch)
        return total

    def _load_entity_batch(
        self, ontology_id: int, entities: list[EntityAnnotation]
    ) -> None:
        with Session(self.engine) as session:
            for entity in entities:
                int_entity_id: int = session.execute(
                    insert(Entity)
                    .values(
                        curie=entity.entity_id,
                        type=entity.kind,
                        ontology_id=ontology_id,
                        is_class=entity.is_class,
                    )
                    .on_conflict_do_update(
                        index_elements=["curie"],
                        set_={
                            "type": Entity.type,
                            "ontology_id": Entity.ontology_id,
                            "is_class": entity.is_class,
                        },
                    )
                    .returning(Entity.entity_id)
                ).scalar_one()

                all_names: list[tuple[str, bool]] = [
                    (entity.preferred_name, True)
                ] + [(s, False) for s in entity.synonyms]

                self._clear_preferred_flags(session, int_entity_id)
                for label, is_preferred in all_names:
                    name_id: int = session.execute(
                        insert(Name)
                        .values(label=label)
                        .on_conflict_do_update(
                            index_elements=["label"],
                            set_={"label": Name.label},
                        )
                        .returning(Name.id)
                    ).scalar_one()
                    session.execute(
                        insert(EntityName)
                        .values(
                            entity_id=int_entity_id,
                            name_id=name_id,
                            is_preferred=is_preferred,
                        )
                        .on_conflict_do_update(
                            index_elements=["entity_id", "name_id"],
                            set_={"is_preferred": is_preferred},
                        )
                    )
            session.commit()

    def rebuild_fts(self) -> None:
        """Rebuild the FTS5 name index from the current Name table contents.

        Used by ``_fts_bulk_reindex`` after a bulk write that ran with the sync
        triggers dropped; not needed for ordinary single-row writes, which the
        triggers keep in sync.
        """
        with self.engine.begin() as conn:
            conn.execute(
                text("INSERT INTO name_fts(name_fts) VALUES ('rebuild')")
            )

    def load_ontology_triples(self, triples: list[ParsedTriple]) -> int:
        """Load ontology triples into the Triple table.

        Resolves CURIE strings to integer entity PKs. Triples whose subject
        or object CURIE is not found in the Entity table are silently skipped
        (this can happen when an ontology imports terms from another ontology
        that has not yet been loaded).

        Returns the number of triples stored.
        """
        if not triples:
            return 0

        with Session(self.engine) as session:
            # Resolve all referenced CURIEs to integer entity IDs in one query
            all_curies = {t.subject_curie for t in triples} | {
                t.object_curie for t in triples if t.object_curie
            }
            curie_to_id: dict[str, int] = dict(
                session.execute(
                    select(Entity.curie, Entity.entity_id).where(
                        Entity.curie.in_(all_curies)
                    )
                ).fetchall()
            )

            count = 0
            for triple in triples:
                subject_id = curie_to_id.get(triple.subject_curie)
                if subject_id is None:
                    continue
                object_id = (
                    curie_to_id.get(triple.object_curie)
                    if triple.object_curie
                    else None
                )
                session.execute(
                    insert(Triple)
                    .values(
                        subject_id=subject_id,
                        predicate=triple.predicate,
                        object_id=object_id,
                        object_literal=triple.object_literal,
                    )
                    .on_conflict_do_nothing()
                )
                count += 1

            session.commit()
        return count

