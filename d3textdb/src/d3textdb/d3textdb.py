    def get_entity_types(self, query: str = "") -> list[EntityAnnotation]:
        """Return all entity classes available for annotation.

        Returns every entity in the ontology (leaf nodes included), optionally
        filtered by ``query`` against preferred name or CURIE.
        Results are sorted by preferred name.
        """
        pref_en = aliased(EntityName)
        pref_name = aliased(Name)

        stmt = (
            select(
                Entity.curie,
                Entity.type,
                pref_name.label.label("preferred_name"),
            )
            .outerjoin(
                pref_en,
                (pref_en.entity_id == Entity.entity_id) & pref_en.is_preferred,
            )
            .outerjoin(pref_name, pref_name.id == pref_en.name_id)
            .where(Entity.curie.isnot(None), Entity.is_class == True)  # noqa: E712
        )

        if query:
            q = f"%{query}%"
            stmt = stmt.where(
                or_(
                    pref_name.label.ilike(q),
                    Entity.curie.ilike(q),
                )
            )

        with Session(self.engine) as session:
            rows = session.execute(stmt).fetchall()

        q_lower = query.strip().lower()

        def rank(e: EntityAnnotation) -> tuple:
            name = e.preferred_name.lower()
            if name == q_lower:
                return (0, name)
            if name.startswith(q_lower):
                return (1, name)
            return (2, name)

        return sorted(
            [
                EntityAnnotation(
                    entity_id=row.curie,
                    preferred_name=row.preferred_name or row.curie or "",
                    kind=row.type or "",
                    synonyms=[],
                    is_class=True,
                )
                for row in rows
            ],
            key=rank,
        )

    def get_ontology_entities(
        self,
        ontology_id: int,
        limit: int = 50,
        offset: int = 0,
        curie_filter: str = "",
        name_filter: str = "",
        type_filter: str = "",
    ) -> tuple[list[EntityAnnotation], int]:
        """Return a page of entities for an ontology and the total count."""
        with Session(self.engine) as session:
            pref_en = aliased(EntityName)
            PrefName = aliased(Name)

            base = (
                select(
                    Entity.entity_id,
                    Entity.curie,
                    Entity.type,
                    PrefName.label.label("preferred_name"),
                )
                .outerjoin(
                    pref_en,
                    (pref_en.entity_id == Entity.entity_id)
                    & pref_en.is_preferred,
                )
                .outerjoin(PrefName, PrefName.id == pref_en.name_id)
                .where(Entity.ontology_id == ontology_id)
            )

            if curie_filter:
                base = base.where(Entity.curie.ilike(f"%{curie_filter}%"))
            if name_filter:
                base = base.where(PrefName.label.ilike(f"%{name_filter}%"))
            if type_filter:
                base = base.where(Entity.type.ilike(f"%{type_filter}%"))

            total: int = (
                session.scalar(
                    select(func.count()).select_from(base.subquery())
                )
                or 0
            )

            rows = session.execute(
                base.order_by(Entity.type, Entity.entity_id)
                .limit(limit)
                .offset(offset)
            ).fetchall()

            return [
                EntityAnnotation(
                    entity_id=row.curie or str(row.entity_id),
                    preferred_name=row.preferred_name or "",
                    kind=row.type,
                    synonyms=[],
                )
                for row in rows
            ], total

    def get_ontology_triples(
        self,
        ontology_id: int,
        limit: int = 50,
        offset: int = 0,
        subject_filter: str = "",
        predicate_filter: str = "",
        object_filter: str = "",
    ) -> tuple[list[dict], int]:
        """Return a page of triples whose subject belongs to the ontology.

        Each dict has: subject_curie, subject_name, predicate, object_curie,
        object_name, object_literal.  Returns (rows, total_count).
        """
        with Session(self.engine) as session:
            SubjectEnt = aliased(Entity)
            ObjectEnt = aliased(Entity)

            base = (
                select(
                    Triple.predicate,
                    Triple.object_literal,
                    SubjectEnt.curie.label("subject_curie"),
                    ObjectEnt.curie.label("object_curie"),
                )
                .join(SubjectEnt, Triple.subject_id == SubjectEnt.entity_id)
                .outerjoin(ObjectEnt, Triple.object_id == ObjectEnt.entity_id)
                .where(SubjectEnt.ontology_id == ontology_id)
            )

            if subject_filter:
                base = base.where(SubjectEnt.curie.ilike(f"%{subject_filter}%"))
            if predicate_filter:
                base = base.where(
                    Triple.predicate.ilike(f"%{predicate_filter}%")
                )
            if object_filter:
                base = base.where(
                    or_(
                        ObjectEnt.curie.ilike(f"%{object_filter}%"),
                        Triple.object_literal.ilike(f"%{object_filter}%"),
                    )
                )

            total: int = (
                session.scalar(
                    select(func.count()).select_from(base.subquery())
                )
                or 0
            )

            rows = session.execute(
                base.order_by(SubjectEnt.curie, Triple.predicate)
                .limit(limit)
                .offset(offset)
            ).fetchall()

            # Resolve preferred names for all referenced CURIEs in one query
            all_curies = {r.subject_curie for r in rows if r.subject_curie} | {
                r.object_curie for r in rows if r.object_curie
            }
            curie_to_name: dict[str, str] = {}
            if all_curies:
                PrefName = aliased(Name)
                for curie, label in session.execute(
                    select(Entity.curie, PrefName.label)
                    .join(
                        EntityName,
                        EntityName.entity_id == Entity.entity_id,
                    )
                    .join(PrefName, PrefName.id == EntityName.name_id)
                    .where(
                        EntityName.is_preferred == True,  # noqa: E712
                        Entity.curie.in_(all_curies),
                    )
                ).fetchall():
                    if curie:
                        curie_to_name[curie] = label

            return [
                {
                    "subject_curie": r.subject_curie,
                    "subject_name": curie_to_name.get(
                        r.subject_curie or "", ""
                    ),
                    "predicate": r.predicate,
                    "object_curie": r.object_curie,
                    "object_name": (
                        curie_to_name.get(r.object_curie, "")
                        if r.object_curie
                        else None
                    ),
                    "object_literal": r.object_literal,
                }
                for r in rows
            ], total

    def get_ontology_properties_by_id(
        self, ontology_id: int
    ) -> list[OntologyProperty]:
        """Return all object properties defined in a specific ontology."""
        with Session(self.engine) as session:
            return list(
                session.scalars(
                    select(OntologyProperty)
                    .where(OntologyProperty.ontology_id == ontology_id)
                    .order_by(OntologyProperty.label)
                )
            )

    def delete_ontology(self, ontology_id: int) -> None:
        """Delete an ontology and cascade-remove its entities, names, and triples.

        Raises OntologyInUseError if any Pointer or Relation rows reference the
        ontology's entities — the ontology must be free of annotations first.
        """
        with Session(self.engine) as session:
            entity_curies = select(Entity.curie).where(
                Entity.ontology_id == ontology_id
            )
            annotation_count = session.scalar(
                select(func.count()).where(
                    or_(
                        exists(
                            select(Pointer.entity_id).where(
                                Pointer.entity_id.in_(entity_curies)
                            )
                        ),
                        exists(
                            select(Relation.relation_id).where(
                                or_(
                                    Relation.subject.in_(entity_curies),
                                    Relation.object.in_(entity_curies),
                                )
                            )
                        ),
                    )
                )
            )
            if annotation_count:
                raise OntologyInUseError(
                    "This ontology has annotations referencing its entities "
                    "and cannot be deleted. Remove the annotations first."
                )

            entity_ids: list[int] = list(
                session.scalars(
                    select(Entity.entity_id).where(
                        Entity.ontology_id == ontology_id
                    )
                )
            )

            if entity_ids:
                session.execute(
                    sa_delete(Triple).where(
                        or_(
                            Triple.subject_id.in_(entity_ids),
                            Triple.object_id.in_(entity_ids),
                        )
                    )
                )

                name_ids: list[int] = list(
                    session.scalars(
                        select(EntityName.name_id).where(
                            EntityName.entity_id.in_(entity_ids)
                        )
                    )
                )

                session.execute(
                    sa_delete(EntityName).where(
                        EntityName.entity_id.in_(entity_ids)
                    )
                )

                if name_ids:
                    still_used = set(
                        session.scalars(
                            select(EntityName.name_id).where(
                                EntityName.name_id.in_(name_ids)
                            )
                        )
                    )
                    orphaned = [n for n in name_ids if n not in still_used]
                    if orphaned:
                        session.execute(
                            sa_delete(Name).where(Name.id.in_(orphaned))
                        )

                session.execute(
                    sa_delete(Entity).where(Entity.entity_id.in_(entity_ids))
                )

            session.execute(
                sa_delete(OntologyProperty).where(
                    OntologyProperty.ontology_id == ontology_id
                )
            )
            session.execute(
                sa_delete(ProjectOntology).where(
                    ProjectOntology.ontology_id == ontology_id
                )
            )
            session.execute(
                sa_delete(Ontology).where(Ontology.ontology_id == ontology_id),
            )
            session.commit()
            # The `name_ad` trigger removes each deleted Name from `name_fts` as
            # part of the bulk delete above, so no rebuild is needed here.

    def set_curation_decision(
        self,
        project_id: int,
        relation_id: int,
        curator_id: UUID,
        verdict: Verdict,
    ) -> None:
        """Upsert a curator's accept/reject verdict on a relation triple."""
        from datetime import datetime, timezone

        with Session(self.engine) as session:
            existing = session.get(
                CurationDecision, (project_id, relation_id, curator_id)
            )
            if existing:
                existing.verdict = verdict
                existing.decided_at = datetime.now(timezone.utc)
            else:
                session.add(
                    CurationDecision(
                        project_id=project_id,
                        relation_id=relation_id,
                        curator_id=curator_id,
                        verdict=verdict,
                        decided_at=datetime.now(timezone.utc),
                    )
                )
            session.commit()

    def get_curation_decisions(
        self, project_id: int, curator_id: UUID
    ) -> dict[int, Verdict]:
        """Return all verdicts a curator has recorded for a project.

        Returns a mapping of relation_id → Verdict.
        """
        with Session(self.engine) as session:
            rows = session.scalars(
                select(CurationDecision).where(
                    CurationDecision.project_id == project_id,
                    CurationDecision.curator_id == curator_id,
                )
            ).all()
        return {row.relation_id: row.verdict for row in rows}
